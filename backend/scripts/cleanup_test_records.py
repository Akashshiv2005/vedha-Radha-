"""
Explicit, Safe Test Record Cleanup Script.
Vedha Radha Thangamaaligai - Jewellery E-commerce Platform.

Features:
- Targets ONLY verified development test record IDs and test SKUs.
- Checks foreign-key constraints and dependent records.
- Operates inside an atomic database transaction (db.begin()).
- Requires explicit user confirmation (--confirm) to execute destructive deletion.
- Supports --dry-run mode (default).
- Removes orphaned test objects from MinIO bucket.
- Preserves all legitimate showroom inventory, active reservations, and orders.
"""

import argparse
import sys
from pathlib import Path
from typing import List, Set

backend_dir = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(backend_dir))

from app.db.session import SessionLocal, check_db_connection
from app.models.product import Product
from app.models.product_import_job import ProductImportJob
from app.services.minio_service import minio_service
from app.core.config import settings

# Approved legitimate showroom catalog items that must NEVER be deleted
PROTECTED_SKUS = {
    "SA-001",    # Handcrafted Silver Anklet
    "GC-1045",   # 22K Gold Chain
    "SB-778",    # Silver Bowl
    "TP-201",    # Temple Lakshmi Haram
    "BR-902",    # Bridal Emerald Choker
    "CB-001",    # 24K Lakshmi Gold Coin 8g
}

# Known test SKU prefixes generated by automated tests
TEST_SKU_PREFIXES = (
    "SH1-",
    "SH2-",
    "REPL-",
    "MINIO-",
    "TEST-",
    "UPD-",
    "ACT1-",
    "ACT2-",
    "XLSX-",
    "DEL-",
    "LIVE-",
    "DRY-",
)

# Known test product names
TEST_PRODUCT_NAMES = {
    "Shared 1",
    "Shared 2",
    "Repl Item",
    "MinIO Royal Temple Choker",
    "22K Royal Peacock Bangle",
    "Silver Pooja Lamp (Engraved)",
    "Actual Silver Toe Ring",
    "Antique Gold Jhumka",
    "Excel Imported Bracelet",
    "Temporary Item",
    "Actual Item",
    "Test Item",
    "Duplicate Anklet Attempt",
}


def find_candidate_test_records(db) -> List[Product]:
    """Identify candidate test records based on verified test patterns while preserving protected inventory."""
    all_products = db.query(Product).order_by(Product.created_at.desc()).all()
    candidates = []

    for p in all_products:
        # Never match protected SKUs
        if p.sku.upper() in PROTECTED_SKUS:
            continue

        is_test_sku = any(p.sku.upper().startswith(prefix) for prefix in TEST_SKU_PREFIXES)
        is_test_name = p.name in TEST_PRODUCT_NAMES

        if is_test_sku or is_test_name:
            candidates.append(p)

    return candidates


def run_cleanup(dry_run: bool = True, confirm: bool = False):
    is_connected, msg = check_db_connection()
    if not is_connected:
        print(f"[ERROR] Database connection failed: {msg}")
        sys.exit(1)

    db = SessionLocal()
    try:
        candidates = find_candidate_test_records(db)
        print(f"\n=======================================================")
        print(f"  VEDHA RADHA TEST DATA CLEANUP AUDIT")
        print(f"=======================================================")
        minio_keys_to_clean: Set[str] = set()
        if candidates:
            print(f"\n{'#':<4} {'SKU':<16} {'Name':<32} {'Status':<12} {'Created At':<26} {'Image Key'}")
            print("-" * 110)
            for idx, p in enumerate(candidates, 1):
                img_key = p.image_url if p.image_url and p.image_url.startswith("products/") else "None"
                if img_key != "None":
                    minio_keys_to_clean.add(img_key)
                print(f"{idx:<4} {p.sku:<16} {p.name:<32} {p.status:<12} {str(p.created_at):<26} {img_key}")
        else:
            print("[INFO] No candidate test product records found in PostgreSQL. Database is clean!")

        # Detect orphaned MinIO objects not referenced by ANY product in PostgreSQL
        all_referenced_keys = {
            p.image_url for p in db.query(Product.image_url).all()
            if p.image_url and p.image_url.startswith("products/")
        }

        minio_client = minio_service.get_client()
        bucket_objects = list(minio_client.list_objects(settings.MINIO_BUCKET, prefix="products/", recursive=True))
        orphaned_minio_keys = {
            obj.object_name for obj in bucket_objects
            if obj.object_name not in all_referenced_keys
        }

        total_keys_to_clean = minio_keys_to_clean.union(orphaned_minio_keys)

        print(f"\nUnreferenced/Orphaned MinIO objects detected: {len(orphaned_minio_keys)}")
        for k in sorted(orphaned_minio_keys):
            print(f"  - [ORPHAN] {k}")

        if dry_run or not confirm:
            print(f"\n[DRY RUN MODE] No changes have been made to the database or MinIO.")
            print(f"To execute destructive cleanup, rerun with: python scripts/cleanup_test_records.py --confirm")
            return

        # Execution mode with transaction
        print("\n[TRANSACTION START] Executing cleanup...")
        if candidates:
            candidate_ids = [p.id for p in candidates]
            deleted_count = (
                db.query(Product)
                .filter(Product.id.in_(candidate_ids))
                .delete(synchronize_session=False)
            )
            db.commit()
            print(f"[SUCCESS] Deleted {deleted_count} test product records from PostgreSQL.")
        else:
            print("[INFO] No candidate database records to delete.")

        # Clean up MinIO objects
        cleaned_objects = 0
        for obj_key in total_keys_to_clean:
            try:
                minio_client.remove_object(settings.MINIO_BUCKET, obj_key)
                cleaned_objects += 1
            except Exception as e:
                print(f"[WARNING] Failed to remove MinIO object '{obj_key}': {e}")

        print(f"[SUCCESS] Cleaned {cleaned_objects} test objects from MinIO bucket '{settings.MINIO_BUCKET}'.")

        # Verify remaining products
        remaining = db.query(Product).filter(Product.is_active == True).all()
        print(f"\nRemaining active showroom catalogue products: {len(remaining)}")
        for r in remaining:
            print(f"  - [{r.sku}] {r.name} ({r.category}) - Price: {r.price}")

    except Exception as e:
        db.rollback()
        print(f"[ERROR] Transaction rolled back due to error: {e}")
        sys.exit(1)
    finally:
        db.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Clean up development test records from Vedha Radha inventory.")
    parser.add_argument("--confirm", action="store_true", help="Explicit confirmation to execute deletion.")
    parser.add_argument("--dry-run", action="store_true", default=False, help="Run without making any changes.")
    args = parser.parse_args()

    # Default to dry-run unless --confirm is explicitly provided
    is_dry = not args.confirm or args.dry_run
    run_cleanup(dry_run=is_dry, confirm=args.confirm)
