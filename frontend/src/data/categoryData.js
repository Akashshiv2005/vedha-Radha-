export const normalizeProductType = (type) => {
  if (!type) return '';
  const lower = type.trim().toLowerCase();
  if (lower === 'gold') return 'Gold';
  if (lower === 'silver') return 'Silver';
  if (lower.includes('coin') || lower.includes('bar')) return 'Coins & Bars';
  return type;
};

export const inferProductTypeFromCategory = (categoryName) => {
  if (!categoryName) return 'Gold';
  const cat = categoryName.trim().toLowerCase();
  if (cat.includes('coin') || cat.includes('bar')) return 'Coins & Bars';
  if (cat.includes('silver') || cat.includes('pooja') || cat.includes('article') || cat.includes('utensil')) return 'Silver';
  return 'Gold';
};

export const getCategoriesForProductType = (productType) => {
  if (!productType) return [];
  const normalized = normalizeProductType(productType);
  return CATEGORIES_BY_PRODUCT_TYPE[normalized] || [];
};

export const getSubcategoriesForTypeAndCategory = (productType, categoryName) => {
  if (!categoryName) return [];
  if (productType) {
    const cats = getCategoriesForProductType(productType);
    const found = cats.find(c => c.name.toLowerCase() === categoryName.trim().toLowerCase());
    if (found) return found.subcategories || [];
  }
  // Fallback to legacy global lookup
  const foundGlobal = JEWELLERY_CATEGORIES.find(
    c => c.name.toLowerCase() === categoryName.trim().toLowerCase()
  );
  return foundGlobal ? foundGlobal.subcategories : [];
};

export const getSubcategoriesForCategory = (categoryName) => {
  return getSubcategoriesForTypeAndCategory(null, categoryName);
};

