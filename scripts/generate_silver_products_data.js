// Convert image into high-resolution 1200x1200px 925 sterling silver luxury studio photograph
async function processSilverPhoto(sourcePath, targetPublicPath, targetDistPath, p, indexInCat) {
  let pipeline = sharp(sourcePath);

  // If source is gold, transform tone to brilliant 925 Sterling Silver / rhodium mirror polish or oxidized antique silver
  const isAntique = p.details && p.details.includes('Antique') || p.details.includes('Oxidized') || p.craftsmanship.includes('Patina');

  if (sourcePath.includes('gold_') || sourcePath.includes('product_necklace') || sourcePath.includes('product_bangles')) {
    if (isAntique) {
      // Antique Oxidized Silver with rich deep contrast and lustrous highlights
      pipeline = pipeline
        .modulate({
          saturation: 0.12,
          brightness: 0.98
        })
        .tint({ r: 235, g: 238, b: 242 });
    } else {
      // Brilliant 925 Sterling Silver / High-Mirror Rhodium Polish
      pipeline = pipeline
        .modulate({
          saturation: 0.15,
          brightness: 1.05
        })
        .tint({ r: 245, g: 248, b: 252 });
    }
  }

  // Crop & perspective variation based on index (0, 1, 2)
  const meta = await pipeline.metadata();
  const w = meta.width || 1200;
  const h = meta.height || 1200;

  let buffer;
  if (indexInCat === 1) {
    // Slight alternate crop
    const cropW = Math.floor(w * 0.92);
    const cropH = Math.floor(h * 0.92);
    buffer = await pipeline
      .extract({ left: Math.floor((w - cropW) / 2), top: Math.floor((h - cropH) / 2), width: cropW, height: cropH })
      .resize(1200, 1200, {
        fit: 'contain',
        background: { r: 248, g: 247, b: 244, alpha: 1 } // Luxury ivory champagne studio background
      })
      .sharpen({ sigma: 1.1, m1: 1.4, m2: 1.8 })
      .jpeg({ quality: 95, progressive: true, chromaSubsampling: '4:4:4' })
      .toBuffer();
  } else if (indexInCat === 2) {
    // Closer macro detail view
    const cropSize = Math.floor(Math.min(w, h) * 0.85);
    buffer = await pipeline
      .extract({ left: Math.floor((w - cropSize) / 2), top: Math.floor((h - cropSize) / 2), width: cropSize, height: cropSize })
      .resize(1200, 1200, {
        fit: 'contain',
        background: { r: 248, g: 247, b: 244, alpha: 1 }
      })
      .sharpen({ sigma: 1.2, m1: 1.5, m2: 2.0 })
      .jpeg({ quality: 95, progressive: true, chromaSubsampling: '4:4:4' })
      .toBuffer();
  } else {
    // Symmetrical primary front view
    buffer = await pipeline
      .resize(1200, 1200, {
        fit: 'contain',
        background: { r: 248, g: 247, b: 244, alpha: 1 }
      })
      .sharpen({ sigma: 1.0, m1: 1.2, m2: 1.5 })
      .jpeg({ quality: 95, progressive: true, chromaSubsampling: '4:4:4' })
      .toBuffer();
  }

  // Verify JPEG magic bytes (FF D8 FF)
  if (buffer[0] !== 0xFF || buffer[1] !== 0xD8 || buffer[2] !== 0xFF) {
    throw new Error(`Generated image is not a valid JPEG: ${targetPublicPath}`);
  }

  fs.writeFileSync(targetPublicPath, buffer);
  fs.writeFileSync(targetDistPath, buffer);
  return buffer.length;
}

